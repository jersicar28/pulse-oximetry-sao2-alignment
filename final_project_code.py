def visualize_synchronization(aligned_df, n_samples=3):
    """
    Visualize the synchronized SpO2 and SaO2 values with improved handling
    """
    # Get unique encounter IDs
    encounter_ids = aligned_df['encounter_id'].unique()

    # Count non-NaN SpO2 values per encounter
    spo2_counts = {}
    for enc_id in encounter_ids:
        enc_data = aligned_df[aligned_df['encounter_id'] == enc_id]
        spo2_counts[enc_id] = (~enc_data['spo2'].isna()).sum()

    # Sort encounters by number of non-NaN SpO2 values (descending)
    sorted_encounters = sorted(spo2_counts.items(), key=lambda x: x[1], reverse=True)

    # Select top n_samples encounters with most non-NaN SpO2 values
    selected_encounters = [enc_id for enc_id, count in sorted_encounters[:n_samples] if count > 0]

    # If we don't have enough encounters with SpO2 data, add some more
    if len(selected_encounters) < n_samples:
        remaining_encounters = [enc_id for enc_id in encounter_ids if enc_id not in selected_encounters]
        selected_encounters.extend(remaining_encounters[:n_samples - len(selected_encounters)])

    # Create subplot for each encounter
    fig, axes = plt.subplots(len(selected_encounters), 1, figsize=(12, 4*len(selected_encounters)))

    if len(selected_encounters) == 1:
        axes = [axes]  # Make axes iterable if only one subplot

    for i, encounter_id in enumerate(selected_encounters):
        encounter_data = aligned_df[aligned_df['encounter_id'] == encounter_id].copy()

        # Sort by timestamp
        encounter_data = encounter_data.sort_values('timestamp')

        # Plot SpO2 and SaO2
        # For SpO2, only plot non-NaN values
        valid_spo2 = ~encounter_data['spo2'].isna()
        if valid_spo2.any():
            axes[i].plot(
                encounter_data.loc[valid_spo2, 'timestamp'],
                encounter_data.loc[valid_spo2, 'spo2'],
                'b-', label='SpO2 (Pulse Oximeter)'
            )

        # For SaO2, only plot non-NaN values
        valid_sao2 = ~encounter_data['sao2'].isna()
        if valid_sao2.any():
            axes[i].plot(
                encounter_data.loc[valid_sao2, 'timestamp'],
                encounter_data.loc[valid_sao2, 'sao2'],
                'r-', label='SaO2 (Blood Gas)'
            )

        axes[i].set_title(f'Encounter ID: {encounter_id[:10]}...')
        axes[i].set_xlabel('Time')
        axes[i].set_ylabel('Oxygen Saturation (%)')
        axes[i].legend()
        axes[i].grid(True)

    plt.tight_layout()
    plt.show()

