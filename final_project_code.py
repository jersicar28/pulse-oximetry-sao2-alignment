def extract_timestamps(data):
    """
    Extract timestamps from the dataset based on its structure
    """
    # Create a copy to avoid SettingWithCopyWarning
    data_copy = data.copy()

    if 'date' in data_copy.columns and 'time' in data_copy.columns:
        # For bloodgas data
        data_copy.loc[:, 'datetime'] = pd.to_datetime(data_copy['date'] + ' ' + data_copy['time'], errors='coerce')
        return data_copy['datetime']
    elif 'encounter_id' in data_copy.columns and 'sample_number' in data_copy.columns:
        # For pulse oximeter data, create a placeholder timestamp
        data_copy.loc[:, 'temp_timestamp'] = data_copy['encounter_id'] + '_' + data_copy['sample_number'].astype(str)
        return data_copy['temp_timestamp']
    elif 'date_calc' in data_copy.columns:
        # For spectrophotometer data
        return pd.to_datetime(data_copy['date_calc'], errors='coerce')
    else:
        # Create a dummy timestamp
        return pd.Series(range(len(data_copy)), index=data_copy.index)

def combine_pulse_oximeter_with_timestamps(pulse_oximeter_df, bloodgas_df, encounter_df):
    """
    Associate timestamps with pulse oximeter readings using encounter data
    """
    print("\n=== Inside combine_pulse_oximeter_with_timestamps function ===")

    # Get start times for each encounter
    encounter_start_times = {}

    # Try to get encounter start times from encounter_df if available
    if 'start_time' in encounter_df.columns and 'encounter_id' in encounter_df.columns:
        for _, row in encounter_df.iterrows():
            if pd.notna(row['start_time']) and pd.notna(row['encounter_id']):
                try:
                    encounter_start_times[row['encounter_id']] = pd.to_datetime(row['start_time'])
                except:
                    pass
        print(f"  Loaded {len(encounter_start_times)} encounter start times from encounter_df")
    else:
        print("  'start_time' or 'encounter_id' column not found in encounter_df")

    # If not available in encounter_df, use bloodgas as reference
    if not encounter_start_times:
        print("  Using bloodgas data as reference for start times")
        encounter_datetime_map = bloodgas_df.groupby('encounter_id').agg({
            'date': 'first',
            'time': 'first'
        }).reset_index()

        for _, row in encounter_datetime_map.iterrows():
            try:
                timestamp = pd.to_datetime(row['date'] + ' ' + row['time'], errors='coerce')
                if pd.notna(timestamp):
                    encounter_start_times[row['encounter_id']] = timestamp
            except:
                pass
        print(f"  Loaded {len(encounter_start_times)} encounter start times from bloodgas data")

    # Now associate timestamps with pulse oximeter readings
    pulse_with_datetime = pulse_oximeter_df.copy()

    # Add a sampling rate column if not present (assumed to be in Hz)
    if 'sampling_rate' not in pulse_with_datetime.columns:
        print("  'sampling_rate' column not found, adding default value of 1.0 Hz")
        pulse_with_datetime.loc[:, 'sampling_rate'] = 1.0  # Default to 1 Hz

    # Calculate datetime for each sample based on encounter start time and sample number
    pulse_with_datetime.loc[:, 'datetime'] = None
    datetime_counter = 0

    # Process each encounter separately
    for encounter_id, group in pulse_with_datetime.groupby('encounter_id'):
        if encounter_id in encounter_start_times:
            base_time = encounter_start_times[encounter_id]

            # Extract the rows for this encounter
            mask = pulse_with_datetime['encounter_id'] == encounter_id

            # Sort by sample number
            sorted_samples = pulse_with_datetime.loc[mask].sort_values('sample_number')

            # Get sampling rate (use median in case of variation)
            try:
                sampling_rate = sorted_samples['sampling_rate'].median()
                if pd.isna(sampling_rate) or sampling_rate <= 0:
                    sampling_rate = 1.0  # Default if invalid
            except:
                sampling_rate = 1.0

            # Calculate time offset for each sample (in seconds)
            time_offsets = sorted_samples['sample_number'] / sampling_rate

            # Filter out NaN values before creating timedeltas
            valid_indices = sorted_samples.index[~pd.isna(time_offsets)]
            valid_offsets = time_offsets[~pd.isna(time_offsets)]

            # Calculate datetime for each valid sample
            try:
                datetimes = [base_time + pd.Timedelta(seconds=float(offset)) for offset in valid_offsets]
                pulse_with_datetime.loc[valid_indices, 'datetime'] = datetimes
                datetime_counter += len(datetimes)
                if encounter_id == list(encounter_start_times.keys())[0]:  # Print for first encounter only
                    print(f"  First encounter: Created {len(datetimes)} timestamps out of {len(sorted_samples)} samples")
            except Exception as e:
                print(f"  Error creating timestamps for encounter {encounter_id[:10]}...: {e}")

    print(f"  Added timestamps to {datetime_counter} rows out of {len(pulse_with_datetime)}")
    print(f"  Non-null datetime values: {pulse_with_datetime['datetime'].notna().sum()}")

    if 'saturation' in pulse_with_datetime.columns:
        non_null_saturation = pulse_with_datetime['saturation'].notna().sum()
        print(f"  Non-null saturation values: {non_null_saturation}")

        # Check if we have any rows with both datetime and saturation
        both_present = ((pulse_with_datetime['datetime'].notna()) &
                        (pulse_with_datetime['saturation'].notna())).sum()
        print(f"  Rows with both datetime and saturation: {both_present}")
    else:
        print("  WARNING: 'saturation' column doesn't exist in pulse oximeter data!")

    return pulse_with_datetime

def synchronize_signals(pulse_oximeter_df, bloodgas_df, encounter_df):
    """
    Synchronize PPG signals with SaO2 values with improved handling
    """
    print("\n=== Inside synchronize_signals function ===")
    # Associates timestamps with pulse oximeter readings
    pulse_with_datetime = combine_pulse_oximeter_with_timestamps(
        pulse_oximeter_df, bloodgas_df, encounter_df
    )

    # Filter out rows with missing date/time
    pulse_with_datetime = pulse_with_datetime.dropna(subset=['datetime'])
    print(f"  After filtering for valid datetimes: {len(pulse_with_datetime)} rows")

    # If saturation column exists, checks valid values
    if 'saturation' in pulse_with_datetime.columns:
        valid_saturation = pulse_with_datetime['saturation'].notna().sum()
        print(f"  Valid saturation values: {valid_saturation}")
    else:
        print("saturation column not found!")

    # Group by encounter_id for proper synchronization
    aligned_data = {}

    # Debug counters
    total_encounters = len(pulse_with_datetime['encounter_id'].unique())
    processed_encounters = 0
    encounters_with_data = 0

    for encounter_id in pulse_with_datetime['encounter_id'].unique():
        # Get pulse oximeter data for this encounter
        encounter_pulse = pulse_with_datetime[pulse_with_datetime['encounter_id'] == encounter_id].copy()

        # Get bloodgas data for this encounter
        encounter_bloodgas = bloodgas_df[bloodgas_df['encounter_id'] == encounter_id].copy()

        # Validation check 1: Ensure we have data for both datasets
        if len(encounter_pulse) == 0 or len(encounter_bloodgas) == 0:
            continue

        # Create timestamps for both datasets
        pulse_timestamps = encounter_pulse['datetime']

        # Convert bloodgas timestamps
        try:
            bloodgas_timestamps = pd.to_datetime(
                encounter_bloodgas['date'] + ' ' + encounter_bloodgas['time'],
                errors='coerce'
            )
        except Exception as e:
            continue

        # Validation check 2: Ensure we have valid timestamps
        if pulse_timestamps.isna().all() or bloodgas_timestamps.isna().all():
            continue

        # Calculate the minimum timestamp
        min_time = min(pulse_timestamps.min(), bloodgas_timestamps.min())

        # Convert timestamps to seconds as pandas Series
        pulse_time_seconds = pd.Series(
            [(ts - min_time).total_seconds() if pd.notna(ts) else np.nan for ts in pulse_timestamps],
            index=pulse_timestamps.index
        )

        bloodgas_time_seconds = pd.Series(
            [(ts - min_time).total_seconds() if pd.notna(ts) else np.nan for ts in bloodgas_timestamps],
            index=bloodgas_timestamps.index
        )

        # Create aligned data for this encounter
        aligned_encounter = {}

        # Handle saturation data
        if 'saturation' in encounter_pulse.columns:
            # Convert saturation to numeric
            encounter_pulse.loc[:, 'saturation'] = pd.to_numeric(encounter_pulse['saturation'], errors='coerce')

            # Drop NaN saturation values
            valid_mask = ~encounter_pulse['saturation'].isna()
            valid_pulse = encounter_pulse[valid_mask].copy()
            valid_time_seconds = pulse_time_seconds[valid_mask]  # Keep as Series, no .values needed

            if len(valid_pulse) >= 2:
                try:
                    # Use robust interpolation method
                    interp_func = interpolate.interp1d(
                        valid_time_seconds.values,  # Convert to numpy array here
                        valid_pulse['saturation'].values,
                        bounds_error=False,
                        fill_value=np.nan,
                        kind='linear'
                    )

                    # Apply interpolation to get SpO2 values at bloodgas times
                    spo2_values = interp_func(bloodgas_time_seconds.values)  # Convert to numpy array here

                    # Store interpolated values
                    aligned_encounter['spo2'] = spo2_values
                    encounters_with_data += 1
                except Exception as e:
                    aligned_encounter['spo2'] = np.full(len(bloodgas_timestamps), np.nan)
            else:
                aligned_encounter['spo2'] = np.full(len(bloodgas_timestamps), np.nan)
        else:
            aligned_encounter['spo2'] = np.full(len(bloodgas_timestamps), np.nan)

        # Add the SaO2 reference values
        if 'so2' in encounter_bloodgas.columns:
            aligned_encounter['sao2'] = encounter_bloodgas['so2'].values
        else:
            aligned_encounter['sao2'] = np.full(len(bloodgas_timestamps), np.nan)

        # Add timestamps and encounter ID
        aligned_encounter['timestamp'] = bloodgas_timestamps.values
        aligned_encounter['encounter_id'] = encounter_id

        # Store this encounter's aligned data
        aligned_data[encounter_id] = pd.DataFrame(aligned_encounter)
        processed_encounters += 1

    # Print summary statistics
    print(f"\nSynchronization summary:")
    print(f"Total encounters: {total_encounters}")
    print(f"Processed encounters: {processed_encounters}")
    print(f"Encounters with valid interpolated data: {encounters_with_data}")

    # Combine all aligned data
    if aligned_data:
        aligned_df = pd.concat(aligned_data.values(), ignore_index=True)
    else:
        aligned_df = pd.DataFrame(columns=['timestamp', 'encounter_id', 'spo2', 'sao2'])

    # Quick check for non-NaN SpO2 values
    non_nan_spo2 = (~aligned_df['spo2'].isna()).sum()
    print(f"Number of non-NaN SpO2 values: {non_nan_spo2} out of {len(aligned_df)}")

    return aligned_df, bloodgas_df

