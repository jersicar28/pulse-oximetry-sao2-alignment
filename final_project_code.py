# Step 2: Analyze error between SpO2 and SaO2 based on melanin levels
def analyze_melanin_error(aligned_df, spectro_df):
    """
    Analyze the error between SpO2 and SaO2 values based on melanin levels

    Parameters:
    - aligned_df: DataFrame containing synchronized SpO2 and SaO2 values
    - spectro_df: DataFrame containing melanin index information

    Returns:
    - error_df: DataFrame with melanin levels and corresponding errors
    - melanin_error_correlation: Correlation coefficient between melanin and error
    - regression_model: Fitted regression model for error correction
    """
    print("\n=== Analyzing Error Between SpO2 and SaO2 Based on Melanin Levels ===")

    # Merge aligned data with spectrophotometer data to get melanin levels
    analysis_df = aligned_df.copy()

    # We need to join based on both patient_id and encounter_id
    # First, get patient_id for each encounter_id
    encounter_patient_map = spectro_df[['encounter_id', 'patient_id']].drop_duplicates()

    # Add patient_id to our analysis dataframe
    analysis_df = analysis_df.merge(
        encounter_patient_map,
        on='encounter_id',
        how='left'
    )

    # Now merge with spectrophotometer data to get melanin index
    analysis_df = analysis_df.merge(
        spectro_df[['patient_id', 'encounter_id', 'melanin_index']],
        on=['patient_id', 'encounter_id'],
        how='left'
    )

    # Calculate the error between SpO2 and SaO2
    analysis_df['error'] = analysis_df['spo2'] - analysis_df['sao2']

    # Filter out rows with NaN values
    valid_data = analysis_df.dropna(subset=['melanin_index', 'error', 'spo2', 'sao2'])

    print(f"Records with valid melanin and error data: {len(valid_data)}")

    if len(valid_data) == 0:
        print("No valid records found with both melanin and error data!")
        return None, None, None

    # Calculate correlation between melanin level and error
    melanin_error_correlation = valid_data['melanin_index'].corr(valid_data['error'])
    print(f"Correlation between melanin index and SpO2-SaO2 error: {melanin_error_correlation:.4f}")

    # Create a scatter plot of melanin index vs. error
    plt.figure(figsize=(10, 6))
    plt.scatter(valid_data['melanin_index'], valid_data['error'], alpha=0.5)
    plt.xlabel('Melanin Index')
    plt.ylabel('SpO2 - SaO2 Error (%)')
    plt.title('Relationship Between Melanin Index and Pulse Oximeter Error')
    plt.grid(True)

    # Fit a regression line to model the relationship
    import statsmodels.api as sm

    # Add a constant for the intercept
    X = sm.add_constant(valid_data['melanin_index'])
    y = valid_data['error']

    try:
        # Fit the regression model
        regression_model = sm.OLS(y, X).fit()

        # Plot the regression line
        x_range = np.linspace(valid_data['melanin_index'].min(), valid_data['melanin_index'].max(), 100)
        y_pred = regression_model.params[0] + regression_model.params[1] * x_range
        plt.plot(x_range, y_pred, 'r-', label=f'y = {regression_model.params[0]:.4f} + {regression_model.params[1]:.4f}x')
        plt.legend()

        # Print regression summary
        print("\nRegression Model Summary:")
        print(f"Intercept: {regression_model.params[0]:.4f}")
        print(f"Slope: {regression_model.params[1]:.4f}")
        print(f"R-squared: {regression_model.rsquared:.4f}")
        print(f"P-value: {regression_model.f_pvalue:.4f}")

        # Show the plot
        plt.show()

        # Calculate summary statistics of the error by melanin index quartiles
        melanin_quartiles = pd.qcut(valid_data['melanin_index'], 4)
        error_by_quartile = valid_data.groupby(melanin_quartiles)['error'].agg(['mean', 'std', 'count'])
        print("\nError by Melanin Index Quartile:")
        print(error_by_quartile)

        # Return the error data and correlation
        return valid_data, melanin_error_correlation, regression_model

    except Exception as e:
        print(f"Error in regression analysis: {e}")
        return valid_data, melanin_error_correlation, None

# Function to correct SpO2 values based on melanin index
def correct_spo2_values(analysis_df, regression_model):
    """
    Apply correction to SpO2 values based on the melanin error regression model

    Parameters:
    - analysis_df: DataFrame with SpO2, SaO2, and melanin_index values
    - regression_model: Fitted regression model for error correction

    Returns:
    - corrected_df: DataFrame with the original and corrected SpO2 values
    """
    print("\n=== Correcting SpO2 Values Based on Melanin Index ===")

    corrected_df = analysis_df.copy()

    # Filter out rows with NaN values
    valid_rows = ~corrected_df['melanin_index'].isna() & ~corrected_df['spo2'].isna()

    if regression_model is not None:
        # Predicted error based on melanin index
        corrected_df.loc[valid_rows, 'predicted_error'] = (
            regression_model.params[0] +
            regression_model.params[1] * corrected_df.loc[valid_rows, 'melanin_index']
        )

        # Subtract the predicted error from SpO2 to get corrected SpO2
        corrected_df.loc[valid_rows, 'corrected_spo2'] = (
            corrected_df.loc[valid_rows, 'spo2'] -
            corrected_df.loc[valid_rows, 'predicted_error']
        )
    else:
        print("No regression model available. Using mean error correction instead.")
        # If no regression model, use the mean error as a simple correction
        mean_error = corrected_df.loc[valid_rows, 'error'].mean()
        corrected_df.loc[valid_rows, 'predicted_error'] = mean_error
        corrected_df.loc[valid_rows, 'corrected_spo2'] = corrected_df.loc[valid_rows, 'spo2'] - mean_error

    print(f"Applied correction to {valid_rows.sum()} SpO2 values")

    return corrected_df

# Step 3: Validate the corrected SpO2 values
def validate_correction(corrected_df):
    """
    Validate the corrected SpO2 values against reference SaO2 values

    Parameters:
    - corrected_df: DataFrame with original SpO2, corrected SpO2, and reference SaO2 values

    Returns:
    - validation_results: Dictionary containing validation metrics
    """
    print("\n=== Validating Corrected SpO2 Values ===")

    # Filter out rows with NaN values
    valid_data = corrected_df.dropna(subset=['spo2', 'corrected_spo2', 'sao2', 'melanin_index'])

    if len(valid_data) == 0:
        print("No valid data for validation!")
        return None

    print(f"Number of samples for validation: {len(valid_data)}")

    # Calculate errors for original and corrected SpO2
    valid_data['original_error'] = valid_data['spo2'] - valid_data['sao2']
    valid_data['corrected_error'] = valid_data['corrected_spo2'] - valid_data['sao2']

    # Calculate evaluation metrics
    from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

    # Original SpO2 metrics
    original_mae = mean_absolute_error(valid_data['sao2'], valid_data['spo2'])
    original_rmse = np.sqrt(mean_squared_error(valid_data['sao2'], valid_data['spo2']))
    original_r2 = r2_score(valid_data['sao2'], valid_data['spo2'])

    # Corrected SpO2 metrics
    corrected_mae = mean_absolute_error(valid_data['sao2'], valid_data['corrected_spo2'])
    corrected_rmse = np.sqrt(mean_squared_error(valid_data['sao2'], valid_data['corrected_spo2']))
    corrected_r2 = r2_score(valid_data['sao2'], valid_data['corrected_spo2'])

    # Calculate correlation between error and melanin index
    original_melanin_error_corr = valid_data['melanin_index'].corr(valid_data['original_error'])
    corrected_melanin_error_corr = valid_data['melanin_index'].corr(valid_data['corrected_error'])

    # Print results
    print("\nValidation Results:")
    print(f"{'Metric':<30} {'Original SpO2':<15} {'Corrected SpO2':<15} {'Improvement':<15}")
    print("-" * 75)
    print(f"{'Mean Absolute Error (MAE)':<30} {original_mae:<15.4f} {corrected_mae:<15.4f} {original_mae - corrected_mae:<15.4f}")
    print(f"{'Root Mean Square Error (RMSE)':<30} {original_rmse:<15.4f} {corrected_rmse:<15.4f} {original_rmse - corrected_rmse:<15.4f}")
    print(f"{'R-squared (R²)':<30} {original_r2:<15.4f} {corrected_r2:<15.4f} {corrected_r2 - original_r2:<15.4f}")
    print(f"{'Melanin-Error Correlation':<30} {original_melanin_error_corr:<15.4f} {corrected_melanin_error_corr:<15.4f} {abs(original_melanin_error_corr) - abs(corrected_melanin_error_corr):<15.4f}")

    # Create validation plots
    plt.figure(figsize=(16, 12))

    # Plot 1: Original SpO2 vs SaO2
    plt.subplot(2, 2, 1)
    plt.scatter(valid_data['sao2'], valid_data['spo2'], alpha=0.5)
    plt.plot([min(valid_data['sao2']), max(valid_data['sao2'])],
             [min(valid_data['sao2']), max(valid_data['sao2'])], 'r--')
    plt.xlabel('SaO2 (%)')
    plt.ylabel('Original SpO2 (%)')
    plt.title(f'Original SpO2 vs SaO2 (R² = {original_r2:.4f})')
    plt.grid(True)

    # Plot 2: Corrected SpO2 vs SaO2
    plt.subplot(2, 2, 2)
    plt.scatter(valid_data['sao2'], valid_data['corrected_spo2'], alpha=0.5)
    plt.plot([min(valid_data['sao2']), max(valid_data['sao2'])],
             [min(valid_data['sao2']), max(valid_data['sao2'])], 'r--')
    plt.xlabel('SaO2 (%)')
    plt.ylabel('Corrected SpO2 (%)')
    plt.title(f'Corrected SpO2 vs SaO2 (R² = {corrected_r2:.4f})')
    plt.grid(True)

    # Plot 3: Original Error vs Melanin Index
    plt.subplot(2, 2, 3)
    plt.scatter(valid_data['melanin_index'], valid_data['original_error'], alpha=0.5)
    plt.xlabel('Melanin Index')
    plt.ylabel('Original Error (SpO2 - SaO2)')
    plt.title(f'Original Error vs Melanin Index (r = {original_melanin_error_corr:.4f})')
    plt.grid(True)

    # Plot 4: Corrected Error vs Melanin Index
    plt.subplot(2, 2, 4)
    plt.scatter(valid_data['melanin_index'], valid_data['corrected_error'], alpha=0.5)
    plt.xlabel('Melanin Index')
    plt.ylabel('Corrected Error (SpO2 - SaO2)')
    plt.title(f'Corrected Error vs Melanin Index (r = {corrected_melanin_error_corr:.4f})')
    plt.grid(True)

    plt.tight_layout()
    plt.show()

    # Create a Bland-Altman plot to visualize agreement between methods
    plt.figure(figsize=(12, 10))

    # Original SpO2 vs SaO2
    plt.subplot(2, 1, 1)
    mean_original = (valid_data['spo2'] + valid_data['sao2']) / 2
    diff_original = valid_data['spo2'] - valid_data['sao2']
    mean_diff_original = np.mean(diff_original)
    std_diff_original = np.std(diff_original)

    plt.scatter(mean_original, diff_original, alpha=0.5)
    plt.axhline(y=mean_diff_original, color='r', linestyle='-', label=f'Mean: {mean_diff_original:.2f}')
    plt.axhline(y=mean_diff_original + 1.96*std_diff_original, color='g', linestyle='--',
                label=f'Upper LoA: {mean_diff_original + 1.96*std_diff_original:.2f}')
    plt.axhline(y=mean_diff_original - 1.96*std_diff_original, color='g', linestyle='--',
                label=f'Lower LoA: {mean_diff_original - 1.96*std_diff_original:.2f}')
    plt.xlabel('Mean of SpO2 and SaO2 (%)')
    plt.ylabel('SpO2 - SaO2 (%)')
    plt.title('Bland-Altman Plot: Original SpO2 vs SaO2')
    plt.legend()
    plt.grid(True)

    # Corrected SpO2 vs SaO2
    plt.subplot(2, 1, 2)
    mean_corrected = (valid_data['corrected_spo2'] + valid_data['sao2']) / 2
    diff_corrected = valid_data['corrected_spo2'] - valid_data['sao2']
    mean_diff_corrected = np.mean(diff_corrected)
    std_diff_corrected = np.std(diff_corrected)

    plt.scatter(mean_corrected, diff_corrected, alpha=0.5)
    plt.axhline(y=mean_diff_corrected, color='r', linestyle='-', label=f'Mean: {mean_diff_corrected:.2f}')
    plt.axhline(y=mean_diff_corrected + 1.96*std_diff_corrected, color='g', linestyle='--',
                label=f'Upper LoA: {mean_diff_corrected + 1.96*std_diff_corrected:.2f}')
    plt.axhline(y=mean_diff_corrected - 1.96*std_diff_corrected, color='g', linestyle='--',
                label=f'Lower LoA: {mean_diff_corrected - 1.96*std_diff_corrected:.2f}')
    plt.xlabel('Mean of Corrected SpO2 and SaO2 (%)')
    plt.ylabel('Corrected SpO2 - SaO2 (%)')
    plt.title('Bland-Altman Plot: Corrected SpO2 vs SaO2')
    plt.legend()
    plt.grid(True)

    plt.tight_layout()
    plt.show()

    # Return validation metrics
    validation_results = {
        'original_mae': original_mae,
        'corrected_mae': corrected_mae,
        'original_rmse': original_rmse,
        'corrected_rmse': corrected_rmse,
        'original_r2': original_r2,
        'corrected_r2': corrected_r2,
        'original_melanin_error_corr': original_melanin_error_corr,
        'corrected_melanin_error_corr': corrected_melanin_error_corr
    }

    return validation_results, valid_data

