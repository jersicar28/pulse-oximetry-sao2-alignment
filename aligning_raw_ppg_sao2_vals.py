def calculate_elapsed_seconds(df, time_column='datetime'):
    """
    Add a new column 'elapsed_seconds' which represents time in seconds since the first timestamp.
    """
    df = df.copy()
    df = df.sort_values(time_column)
    start_time = df[time_column].iloc[0]
    df['elapsed_seconds'] = (df[time_column] - start_time).dt.total_seconds()
    return df


