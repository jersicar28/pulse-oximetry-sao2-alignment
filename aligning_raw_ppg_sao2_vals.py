def prepare_data(pulse_oximeter_df, bloodgas_df, patient_df, encounter_df, spectro_df):
    """
    Prepare and align data from different sources for SpO2 analysis
    """
    # For bloodgas_df, combine date and time columns into a single datetime column
    # Convert date and time separately
    bloodgas_df['date'] = pd.to_datetime(bloodgas_df['date'])
    bloodgas_df['time'] = pd.to_datetime(bloodgas_df['time'])

    # Combine them
    bloodgas_df['datetime'] = pd.to_datetime(
      bloodgas_df['date'].dt.strftime('%Y-%m-%d') + ' ' +
      bloodgas_df['time'].dt.strftime('%H:%M:%S')
    )

    # For pulse_oximeter_df, we need to link it to timestamps
    # If it has sample numbers but no timestamps, we need to create timestamps
    # Let's assume sample_number corresponds to seconds from the start of recording
    if 'encounter_id' in pulse_oximeter_df.columns and 'sample_number' in pulse_oximeter_df.columns:
      pulse_data = []
      for encounter_id, group in pulse_oximeter_df.groupby('encounter_id'):
        if encounter_id in encounter_df['encounter_id'].values:
          encounter_date = encounter_df.loc[encounter_df['encounter_id'] == encounter_id, 'encounter_date'].iloc[0]
          group_copy = group.copy()
          group_copy = group_copy.dropna(subset=['sample_number'])  # Drop rows with missing sample_number
          base_date = pd.to_datetime(encounter_date)
          group_copy['datetime'] = base_date + pd.to_timedelta(group_copy['sample_number'], unit='s')
          pulse_data.append(group_copy)
      if pulse_data:
        pulse_df = pd.concat(pulse_data)
        pulse_df = pulse_df.dropna(subset=['datetime'])  # Ensure no null datetimes
      else:
        raise ValueError("Could not create timestamps for pulse oximeter data")


    # Extract reference values
    # For bloodgas, we'll use 'so2' as the reference SaO2 value
    if 'so2' in bloodgas_df.columns:
        reference_df = bloodgas_df[['encounter_id', 'datetime', 'so2']].copy()
        reference_df.rename(columns={'so2': 'reference_sao2'}, inplace=True)
    else:
        raise ValueError("Missing 'so2' column in bloodgas_df")

    # Extract SpO2 values from pulse oximeter
    if 'saturation' in pulse_df.columns:
        spo2_df = pulse_df[['encounter_id', 'datetime', 'saturation']].copy()
        spo2_df.rename(columns={'saturation': 'pulse_spo2'}, inplace=True)
    else:
        raise ValueError("Missing 'saturation' column in pulse_oximeter_df")

    # Merge data by encounter_id and datetime
    # First, sort both dataframes by datetime
    reference_df = reference_df.sort_values(['encounter_id', 'datetime'])
    spo2_df = spo2_df.sort_values(['encounter_id', 'datetime'])

    # Now use merge_asof to align the data within each encounter
    merged_data = []
    for encounter_id, ref_group in reference_df.groupby('encounter_id'):
        spo2_group = spo2_df[spo2_df['encounter_id'] == encounter_id]

        if not spo2_group.empty:
            encounter_merged = pd.merge_asof(
                ref_group,
                spo2_group,
                on='datetime',
                by='encounter_id',
                direction='nearest',
                tolerance=pd.Timedelta('5s')  # 5 second tolerance
            )
            merged_data.append(encounter_merged)

    if merged_data:
        final_df = pd.concat(merged_data)

        # Check if we have the required data for analysis
        if 'reference_sao2' in final_df.columns and 'pulse_spo2' in final_df.columns:
            return final_df
        else:
            raise ValueError("Missing required columns after merging")
    else:
        raise ValueError("No data after merging")

def extract_ppg_features(spectro_df, wavelength_features=None):
    """
    Extract features from spectrophotometer data that can be used as proxies for PPG signals

    Parameters:
    -----------
    spectro_df : pandas.DataFrame
        The spectrophotometer data
    wavelength_features : list, optional
        List of wavelength columns to use. If None, will use default red and IR proxies

    Returns:
    --------
    DataFrame with encounter_id, patient_id and extracted red/IR signal proxies
    """
    if wavelength_features is None:
        # Use wavelengths closest to red (660nm) and IR (880nm)
        red_proxy = 'km660'  # 660nm wavelength
        ir_proxy = 'km700'   # Closest to 880nm in the available data

        wavelength_features = [red_proxy, ir_proxy]

    # Check if the required columns exist
    for col in wavelength_features + ['encounter_id', 'patient_id']:
        if col not in spectro_df.columns:
            raise ValueError(f"Missing column {col} in spectrophotometer data")

    # Extract features
    feature_df = spectro_df[['encounter_id', 'patient_id'] + wavelength_features].copy()

    # Rename columns to match our processing pipeline
    feature_df.rename(columns={
        wavelength_features[0]: 'red_signal',
        wavelength_features[1]: 'ir_signal'
    }, inplace=True)

    return feature_df

def calculate_r_ratio_from_saturation(spo2_values):
    """
    Calculate R values from SpO2 using the inverse of the calibration equation.
    This is useful when we don't have raw PPG signals but do have SpO2 values.

    Using the equation: SpO2 = a*R^2 + b*R + c
    We can solve for R using the quadratic formula.

    Parameters:
    -----------
    spo2_values : array-like
        SpO2 values as percentages

    Returns:
    --------
    Array of R values
    """
    # Default calibration coefficients
    a, b, c = 1.5958422, -34.6596622, 112.6898759  # From MAX30101 defaults in Table 1

    # Solve quadratic equation: a*R^2 + b*R + (c - SpO2) = 0
    r_values = []

    for spo2 in spo2_values:
        if a == 0:  # Linear case
            r = (spo2 - c) / b if b != 0 else np.nan
        else:  # Quadratic case
            discriminant = b**2 - 4*a*(c - spo2)

            if discriminant < 0:
                r = np.nan
            else:
                # Usually the smaller root is the correct one for SpO2 calibration
                r1 = (-b + np.sqrt(discriminant)) / (2*a)
                r2 = (-b - np.sqrt(discriminant)) / (2*a)

                # Choose the solution that makes sense for SpO2 (typically R is in a specific range)
                if 0 <= r2 <= 1.5:
                    r = r2
                elif 0 <= r1 <= 1.5:
                    r = r1
                else:
                    r = min(r1, r2) if r1 > 0 and r2 > 0 else max(r1, r2)

        r_values.append(r)

    return np.array(r_values)

def smooth_signal(y, window_size=5):
    """
    Smooth a signal using simple moving average.

    Parameters:
    -----------
    y : array-like
        The signal to smooth
    window_size : int
        Size of the moving window (default=5)

    Returns:
    --------
    Smoothed signal (same length as input)
    """
    y = pd.Series(y)
    smoothed = y.rolling(window=window_size, center=True, min_periods=1).mean()
    return smoothed.values

