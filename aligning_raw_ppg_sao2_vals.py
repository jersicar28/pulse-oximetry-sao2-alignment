def calculate_r_values(red_ac, red_dc, ir_ac, ir_dc):
    #Calculate R values according to the provided formula on pg 5 of manual: R = (ACred/DCred)/(ACired/DCired)

    per_red = red_ac / red_dc
    per_ir = ir_ac / ir_dc
    r_values = per_red / per_ir
    return r_values

def detect_stable_plateaus(spo2_values, window_size=5, std_threshold=1.0):
    """
    Detect stable plateaus in SpO2 data as shown in Fig. 9 and 10 of the document and returns mask of stable points (array of bools format).
    """
    is_stable = np.zeros_like(spo2_values, dtype=bool)

    # Edge case handling
    if len(spo2_values) < window_size:
        return is_stable

    # Calculate rolling standard deviation
    for i in range(window_size, len(spo2_values) - window_size):
        window = spo2_values[i-window_size:i+window_size]
        std = np.std(window)

        if std < std_threshold:
            is_stable[i] = True

    return is_stable

def find_valid_indices_for_spo2_level(spo2_values, r_values, level, std_multiplier=2):
    """
    Given a specific SpO2 level, find indices of valid (non-outlier) R-values.
    """
    level_mask = np.isclose(np.round(spo2_values), level)

    if np.sum(level_mask) <= 1:
        return np.array([], dtype=int)  # No valid points if not enough data

    r_at_level = r_values[level_mask]
    mean_r = np.mean(r_at_level)
    std_r = np.std(r_at_level)

    valid_r_mask = (r_at_level >= mean_r - std_multiplier * std_r) & \
                   (r_at_level <= mean_r + std_multiplier * std_r)

    level_indices = np.where(level_mask)[0]
    valid_indices = level_indices[valid_r_mask]

    return valid_indices

def remove_outliers(r_values, spo2_values, std_multiplier=2):
    """
  Remove outliers by:
    a. Find the R values that are equal to 100% SpO (above)
    b. Find the mean (μ) and standard deviation (σ) of the corresponding R values.
    c. Remove points that are outside the range of μ± 2σ.
    d. Repeat step a–step c for each SpO level (i.e., 100%, 99%, 98%, …, 70%).
    """
    unique_spo2 = np.unique(np.round(spo2_values))
    valid_indices = []

    for level in unique_spo2:
        valid_level_indices = find_valid_indices_for_spo2_level(
            spo2_values, r_values, level, std_multiplier
        )
        valid_indices.extend(valid_level_indices)

    valid_mask = np.zeros_like(spo2_values, dtype=bool)
    valid_mask[valid_indices] = True
    return valid_mask


def fit_calibration_curve(r_values, spo2_values, order=2):
    """
    Fit a calibration curve to the R vs SpO2 data.
    Returns the polynomial coefficients [a, b, c] for SpO2 = a*R^2 + b*R + c
    """
    if order == 1:
        # First order polynomial: SpO2 = b*R + c
        coefficients = np.polyfit(r_values, spo2_values, 1)
        return [0, coefficients[0], coefficients[1]]
    else:
        # Second order polynomial: SpO2 = a*R^2 + b*R + c
        coefficients = np.polyfit(r_values, spo2_values, 2)
        return coefficients

def calculate_spo2(r_values, coefficients):
    """
    Calculate SpO2 values using the calibration coefficients.
    SpO2 = a*R^2 + b*R + c
    """
    a, b, c = coefficients
    spo2_values = a * r_values**2 + b * r_values + c
    # Clip values to the valid SpO2 range of 0-100%
    spo2_values = np.clip(spo2_values, 0, 100)
    return spo2_values

def evaluate_performance(actual_spo2, predicted_spo2):
    """
    Calculate RMSE as described in the document since RMSE must be below 3.0% for transmissive pulse oximetry and below 3.5% for reflective pulse oximetry
    Returns RMSE value using RMSE equation on pg 14 and a plot of actual vs predicted values.
    """
    rmse = sqrt(mean_squared_error(actual_spo2, predicted_spo2))

    # Plot actual vs predicted
    plt.figure(figsize=(10, 6))
    plt.scatter(actual_spo2, predicted_spo2, alpha=0.5)
    plt.plot([70, 100], [70, 100], 'r--')  # Perfect prediction line
    plt.xlabel('Reference SpO2 (%)')
    plt.ylabel('Estimated SpO2 (%)')
    plt.title(f'Actual vs Predicted SpO2 (RMSE = {rmse:.2f}%)')
    plt.grid(True)

    return rmse

def leave_one_out_cross_validation(r_values_by_subject, spo2_values_by_subject):
    """
    Perform leave-one-out cross-validation as described on pg. 14 of the document to demonstrate the algorithm evaluation against
    clinically relevant accuracy requirements
    """
    n_subjects = len(r_values_by_subject)
    rmse_values = []

    for test_idx in range(n_subjects):
        # Split data into training and test sets
        train_r = []
        train_spo2 = []

        for i in range(n_subjects):
            if i != test_idx:
                train_r.extend(r_values_by_subject[i])
                train_spo2.extend(spo2_values_by_subject[i])

        train_r = np.array(train_r)
        train_spo2 = np.array(train_spo2)

        # Fit calibration curve on training data
        coefficients = fit_calibration_curve(train_r, train_spo2)

        # Evaluate on test data
        test_r = np.array(r_values_by_subject[test_idx])
        test_spo2 = np.array(spo2_values_by_subject[test_idx])
        predicted_spo2 = calculate_spo2(test_r, coefficients)

        # Calculate RMSE for this fold
        rmse = sqrt(mean_squared_error(test_spo2, predicted_spo2))
        rmse_values.append(rmse)

        print(f"Subject {test_idx+1} RMSE: {rmse:.2f}%")

    overall_rmse = np.mean(rmse_values)
    print(f"Overall RMSE: {overall_rmse:.2f}%")
    return overall_rmse, rmse_values

def process_ppg_signals(red_signal, ir_signal, sampling_rate):
    """
    Process raw PPG signals to extract AC and DC components.
    """
    # Initialize arrays
    red_ac = np.zeros_like(red_signal, dtype=float)
    red_dc = np.zeros_like(red_signal, dtype=float)
    ir_ac = np.zeros_like(ir_signal, dtype=float)
    ir_dc = np.zeros_like(ir_signal, dtype=float)

    window_size = sampling_rate  # typically 1 sec worth of data

    # Calculate DC component (mean of a window)
    for i in range(window_size, len(red_signal)):
        red_window = red_signal[i-window_size:i]
        ir_window = ir_signal[i-window_size:i]
        red_dc[i] = np.mean(red_window)
        ir_dc[i] = np.mean(ir_window)
        red_ac[i] = red_signal[i] - red_dc[i]
        ir_ac[i] = ir_signal[i] - ir_dc[i]

    # Calculate AC amplitude (peak-to-peak) over another window
    red_ac_amp = np.zeros_like(red_signal, dtype=float)
    ir_ac_amp = np.zeros_like(ir_signal, dtype=float)

    for i in range(window_size*2, len(red_signal)):
        red_ac_window = red_ac[i-window_size:i]
        ir_ac_window = ir_ac[i-window_size:i]
        red_ac_amp[i] = np.max(red_ac_window) - np.min(red_ac_window)
        ir_ac_amp[i] = np.max(ir_ac_window) - np.min(ir_ac_window)

    # Important: Trim arrays so they match
    start_idx = window_size * 2
    return (
        red_ac_amp[start_idx:],
        red_dc[start_idx:],
        ir_ac_amp[start_idx:],
        ir_dc[start_idx:]
    )


